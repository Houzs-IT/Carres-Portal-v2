// Carres: the engine runs Carres as ONE company on Houzs's main-company row (code 'HOUZS'), and Houzs's
// code hard-wires that row's id as 1 (binding-mode.ts HARD_BOUND_COMPANY_ID, the chart-of-accounts import).
// These pin the database build to exactly that: one company row, code HOUZS, id 1, held by step 2005.
import { readFileSync, readdirSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { describe, expect, it } from "vitest";
import { HARD_BOUND_COMPANY_ID } from "../src/scm/lib/binding-mode";

const BACKEND = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const DIR = path.join(BACKEND, "scripts/carres-db/migrations");
const files = readdirSync(DIR).filter((f) => f.endsWith(".sql")).sort();
const read = (f: string) => readFileSync(path.join(DIR, f), "utf8");
/** Drop SQL line comments so a REVERSAL note is not read as a statement. */
const code = (sql: string) => sql.replace(/--[^\n]*/g, "");

describe("Carres company id", () => {
  it("the code expects company id 1", () => {
    expect(HARD_BOUND_COMPANY_ID).toBe(1);
  });

  it("the build inserts exactly one company, code HOUZS, first", () => {
    const inserts = files.flatMap((f) =>
      [...code(read(f)).matchAll(/insert\s+into\s+(?:public\.)?companies\b[^;]*;/gi)].map((m) => ({ f, sql: m[0] })),
    );
    expect(inserts).toHaveLength(1);
    expect(inserts[0].f).toBe(files[0]);
    expect(inserts[0].sql).toMatch(/values\s*\(\s*'HOUZS'/i);
    // Into a fresh identity column, so it is id 1; step 2005 then proves it.
    expect(read(files[0])).toMatch(/create table public\.companies \(\s*id bigint generated by default as identity primary key/i);
  });

  it("nothing updates or deletes companies, re-seeds its identity, or truncates it", () => {
    const hits = files.filter((f) =>
      /(update\s+(?:public\.)?companies\b|delete\s+from\s+(?:public\.)?companies\b|truncate[^;]*\bcompanies\b|alter\s+table\s+(?:public\.)?companies\b[^;]*\b(restart|identity|alter\s+column\s+id)\b|setval\s*\([^)]*companies)/i
        .test(code(read(f))),
    );
    expect(hits).toEqual([]);
  });

  it("step 2005 stops the build unless the one company is id 1 / HOUZS, and guards it afterwards", () => {
    const guard = files.find((f) => /^2005_/.test(f));
    expect(guard).toBeDefined();
    const sql = code(read(guard!));
    expect(sql).toMatch(/v_count <> 1/);
    expect(sql).toMatch(/v_code <> 'HOUZS' OR v_id <> 1/);
    expect(sql).toMatch(/BEFORE UPDATE OF id, code OR DELETE ON public\.companies/);
    // It runs after the insert (apply.mjs applies files in name order).
    expect(files.indexOf(guard!)).toBeGreaterThan(0);
  });
});
